import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, describe, it } from 'node:test';
import { placeCookies } from '../src/music/ytdlp-cookies';

const root = mkdtempSync(join(tmpdir(), 'yt-cookies-'));
after(() => rmSync(root, { recursive: true, force: true }));

const EXPORT = Buffer.from(
  '# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t0\tSID\told\n',
);
const REFRESHED = '# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.\n';

let n = 0;
function freshDir(): string {
  return join(root, String(n++));
}

describe('placeCookies', () => {
  it('writes the export the first time', () => {
    const dir = freshDir();
    assert.equal(placeCookies(EXPORT, dir), 'written');
    assert.deepEqual(readFileSync(join(dir, 'yt-cookies.txt')), EXPORT);
  });

  it('keeps the copy yt-dlp refreshed while the export is the same', () => {
    const dir = freshDir();
    placeCookies(EXPORT, dir);
    writeFileSync(join(dir, 'yt-cookies.txt'), REFRESHED);
    assert.equal(placeCookies(EXPORT, dir), 'kept');
    assert.equal(readFileSync(join(dir, 'yt-cookies.txt'), 'utf8'), REFRESHED);
  });

  it('lets a new export take over', () => {
    const dir = freshDir();
    placeCookies(EXPORT, dir);
    writeFileSync(join(dir, 'yt-cookies.txt'), REFRESHED);
    const next = Buffer.from(
      '# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t0\tSID\tnew\n',
    );
    assert.equal(placeCookies(next, dir), 'written');
    assert.deepEqual(readFileSync(join(dir, 'yt-cookies.txt')), next);
  });

  it('rewrites a missing or damaged copy', () => {
    const dir = freshDir();
    placeCookies(EXPORT, dir);
    writeFileSync(join(dir, 'yt-cookies.txt'), '.youtube.com\tTRUE\t/\tTR');
    assert.equal(placeCookies(EXPORT, dir), 'written');
    rmSync(join(dir, 'yt-cookies.txt'));
    assert.equal(placeCookies(EXPORT, dir), 'written');
    assert.deepEqual(readFileSync(join(dir, 'yt-cookies.txt')), EXPORT);
  });
});
